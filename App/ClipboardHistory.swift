import Cocoa
import Carbon

/// 클립보드 기록: 복사한 글자를 최근 20개까지 맥 안에만 보관 (안드판 ClipboardHistory와 같음)
final class ClipboardHistory {
    static let shared = ClipboardHistory()

    struct Clip: Codable {
        var text: String
        var at: Date
    }

    static let maxItems = 20
    /// 보관 시간(초). 0 = 계속
    static let keepOptions: [(String, TimeInterval)] = [("10분", 600), ("1시간", 3600), ("1일", 86400), ("계속", 0)]

    private let defaults = UserDefaults.standard
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?

    var enabled: Bool {
        get { defaults.object(forKey: "clipOn") as? Bool ?? true }
        set { defaults.set(newValue, forKey: "clipOn"); if !newValue { clear() } }
    }

    var keep: TimeInterval {
        get { defaults.object(forKey: "clipKeep") as? Double ?? 86400 }
        set { defaults.set(newValue, forKey: "clipKeep") }
    }

    /// 최근 것부터, 보관 시간 지난 것은 뺌
    var clips: [Clip] {
        let all = (defaults.data(forKey: "clips")).flatMap { try? JSONDecoder().decode([Clip].self, from: $0) } ?? []
        guard keep > 0 else { return all }
        let cutoff = Date().addingTimeInterval(-keep)
        return all.filter { $0.at >= cutoff }
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
    }

    func clear() {
        defaults.removeObject(forKey: "clips")
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard enabled else { return }
        // 비밀번호 관리자 등이 '민감/임시'로 표시한 복사, 비밀번호 칸 입력 중의 복사는 기록 안 함
        let types = Set((pb.types ?? []).map(\.rawValue))
        let sensitive = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                         "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        if sensitive.contains(where: types.contains) || IsSecureEventInputEnabled() { return }
        guard let text = pb.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        var list = clips.filter { $0.text != text }
        list.insert(Clip(text: text, at: Date()), at: 0)
        if list.count > Self.maxItems { list = Array(list.prefix(Self.maxItems)) }
        if let data = try? JSONEncoder().encode(list) { defaults.set(data, forKey: "clips") }
    }

    static func ago(_ d: Date) -> String {
        let min = Int(Date().timeIntervalSince(d) / 60)
        if min < 1 { return "방금" }
        if min < 60 { return "\(min)분 전" }
        if min < 24 * 60 { return "\(min / 60)시간 전" }
        return "\(min / (24 * 60))일 전"
    }
}
